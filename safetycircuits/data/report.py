"""Write results/data_report.md from the prepared data.

Harmful prompts are never printed: the report shows counts, lengths and ids only.
Run: python -m safetycircuits.data.report
"""

import json
import statistics
from collections import Counter
from itertools import combinations

from safetycircuits.config import RESULTS_DIR
from safetycircuits.data.prepare import DATA_DIR, INTERIM, key

NEAR_DUP_JACCARD = 0.8


def read(name: str) -> list[dict]:
    with open(INTERIM / name, encoding="utf-8") as f:
        return [json.loads(line) for line in f]


def length_row(label: str, items: list[dict]) -> str:
    words = sorted(len(i["text"].split()) for i in items)
    return (
        f"| {label} | {len(items)} | {statistics.mean(words):.1f} | "
        f"{statistics.median(words):.0f} | {words[0]}–{words[-1]} |"
    )


def near_duplicates(items: list[dict]) -> int:
    sets = [set(key(i["text"]).split()) for i in items]
    return sum(
        1
        for a, b in combinations(sets, 2)
        if a and b and len(a & b) / len(a | b) >= NEAR_DUP_JACCARD
    )


def starts_with_verb_share(items: list[dict]) -> Counter:
    return Counter(i["text"].split()[0].lower() for i in items)


def main() -> None:
    harmful, harmless, xstest = read("harmful.jsonl"), read("harmless.jsonl"), read("xstest.jsonl")
    splits = json.loads((DATA_DIR / "splits.json").read_text())
    quality = json.loads((DATA_DIR / "quality.json").read_text())
    manifest = json.loads((DATA_DIR / "manifest.json").read_text())

    by_source = Counter(i["source"] for i in harmful)
    by_cat = Counter(i.get("category", "advbench (no category)") for i in harmful)
    xs_label = Counter(i["label"] for i in xstest)
    xs_type = Counter((i["label"], i["type"]) for i in xstest)
    first_words = starts_with_verb_share(harmful)
    top_first = ", ".join(f"{w} ({n})" for w, n in first_words.most_common(5))
    near = near_duplicates(harmful)
    harmful_share = 100 * len(harmful) / (len(harmful) + len(harmless))
    a = quality["alpaca"]
    fl = quality["flores"]

    lines = [
        "# Data report",
        "",
        "Generated by `python -m safetycircuits.data.report`. Harmful prompts are not shown here:",
        f"only counts, lengths and ids. Seed: {splits['seed']}.",
        "",
        "## Sources and licences",
        "",
        "| File | Licence | Bytes | SHA-256 (first 12) |",
        "|---|---|---|---|",
    ]
    for name, m in manifest.items():
        lines.append(f"| {name} | {m['licence']} | {m['bytes']:,} | {m['sha256'][:12]} |")

    lines += [
        "",
        "## Counts",
        "",
        "| Set | Count | Note |",
        "|---|---|---|",
        f"| Harmful (total) | {len(harmful)} | AdvBench {by_source['advbench']} + "
        f"HarmBench standard {by_source['harmbench']} |",
        f"| Harmless (Alpaca-cleaned sample) | {len(harmless)} | from {a['eligible']:,} eligible |",
        f"| XSTest | {len(xstest)} | safe {xs_label['safe']}, unsafe {xs_label['unsafe']} |",
        f"| Translation set | {len(splits['translate_ids'])} | harmful, from the test split |",
        f"| FLORES control sentences | {len(splits['flores_control_indices'])} | per language |",
        "",
        f"**Class balance:** harmful {len(harmful)} vs harmless {len(harmless)} "
        f"({harmful_share:.0f}% / {100 - harmful_share:.0f}%).",
        "",
        "### Splits (ids only, in `data/splits.json`)",
        "",
        "| Split | Harmful | Harmless |",
        "|---|---|---|",
    ]
    for name in splits["fractions"]:
        lines.append(
            f"| {name} | {len(splits['harmful'][name])} | {len(splits['harmless'][name])} |"
        )

    lines += ["", "### HarmBench semantic categories (standard behaviours)", ""]
    lines += [f"- {c}: {n}" for c, n in sorted(by_cat.items()) if c != "advbench (no category)"]
    lines += [
        "",
        "### XSTest by type",
        "",
        "| Label | Type | Count |",
        "|---|---|---|",
    ]
    lines += [f"| {lab} | {t} | {n} |" for (lab, t), n in sorted(xs_type.items())]

    lines += [
        "",
        "## Length (words per prompt)",
        "",
        "| Set | N | Mean | Median | Range |",
        "|---|---|---|---|---|",
        length_row("Harmful (all)", harmful),
        length_row("Harmful (AdvBench)", [i for i in harmful if i["source"] == "advbench"]),
        length_row("Harmful (HarmBench)", [i for i in harmful if i["source"] == "harmbench"]),
        length_row("Harmless (Alpaca)", harmless),
        length_row("XSTest safe", [i for i in xstest if i["label"] == "safe"]),
        length_row("XSTest unsafe", [i for i in xstest if i["label"] == "unsafe"]),
        "",
        "## Sample records (harmless and XSTest-safe only)",
        "",
    ]
    lines += [f"- `{i['id']}`: {i['text']}" for i in harmless[:3]]
    lines += [f"- `{i['id']}`: {i['text']}" for i in xstest[:2]]
    lines += [
        "- Harmful records: ids look like `advbench-0001` and `harmbench-<behaviour id>`. "
        "Text is kept out of the repo and out of this report.",
    ]

    lines += [
        "",
        "## Quality problems found",
        "",
        f"- **Exact duplicates:** AdvBench {quality['advbench_duplicates_removed']}, "
        f"HarmBench plus overlap with AdvBench "
        f"{quality['harmbench_duplicates_or_advbench_overlap_removed']} (after lower-casing and "
        f"stripping punctuation).",
        f"- **Near duplicates:** {near} harmful prompt pairs share at least "
        f"{NEAR_DUP_JACCARD:.0%} of their words. They are kept, but they can land in different "
        f"splits, so a direction fitted on train sees near-copies of some test prompts. This makes "
        f"test scores slightly optimistic.",
        f"- **HarmBench:** {quality['harmbench_non_standard_excluded']} behaviours were excluded "
        f"because they are contextual or copyright tasks that need extra input.",
        f"- **Style difference between sets:** AdvBench prompts are short and repetitive, and most "
        f"start with the same few verbs (top first words: {top_first}). Alpaca prompts are varied "
        f"questions and instructions. A refusal direction could partly pick up this style "
        f"difference instead of harmfulness. XSTest (safe prompts that look unsafe) is the check, "
        f"and Step 6 should add a style-matched control.",
        f"- **Alpaca-cleaned:** {a['with_input']:,} of {a['total']:,} items need an extra input "
        f"field and were dropped. {a['too_short_or_long']} were outside 20–200 characters and "
        f"{a['duplicates']} were duplicates. Licence is disputed (see README).",
        f"- **FLORES-200:** devtest has {fl['lines']['eng_Latn']} lines in English, Twi, French "
        f"and Swahili, with {sum(fl['empty'].values())} empty lines. FLORES is benign "
        f"Wikipedia-style text, so harmful prompts in Twi, French and Swahili "
        f"must be machine-translated "
        f"(Step 5, GPU notebook). Translation quality for Twi is unchecked until then.",
        "- **No labels were audited by hand.** Harmfulness comes from the benchmark authors.",
        "",
    ]
    RESULTS_DIR.mkdir(exist_ok=True)
    (RESULTS_DIR / "data_report.md").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("wrote results/data_report.md")


if __name__ == "__main__":
    main()
